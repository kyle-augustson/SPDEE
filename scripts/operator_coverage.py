"""Run the operator coverage matrix and write docs/OPERATOR_COVERAGE.md.

    python scripts/operator_coverage.py [--json out.json] [--cores a,b] [--m 0,1,2]

Each cell is a manufactured-solution boundary-value problem for one IR
operator on one (core, geometry), solved at two resolutions; see
``tests/analytic/manufactured.py`` for how each core is driven. A cell
is PASS with the measured order, REFUSED with the core's own reason, or
FAIL. The three azimuthal orders of a cell are collapsed into one entry;
a cell whose azimuthal orders disagree is listed per m.

``--from-json`` rebuilds the table from earlier dumps and re-applies the
current pass criterion to the errors they hold, so the thresholds can be
changed without re-running the matrix.
"""

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

from analytic.manufactured import (  # noqa: E402
    CASES, CORE_SPECS, GEOMETRIES, Outcome, measure, verdict,
)

M_VALUES = (0, 1, 2)


def _commit():
    try:
        out = subprocess.run(["git", "-C", str(ROOT), "rev-parse", "--short", "HEAD"],
                             capture_output=True, text=True, check=True)
        return out.stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def _short(reason, limit=90):
    text = " ".join(reason.split())
    for prefix in ("NotImplementedError: ", "TypeError: ", "RuntimeError: ", "ValueError: "):
        if text.startswith(prefix):
            text = text[len(prefix):]
    return text if len(text) <= limit else text[:limit - 1] + "…"


def _one(outcome):
    if outcome.status == "PASS":
        return f"PASS p={outcome.order:.1f}"
    if outcome.status == "REFUSED":
        return "REFUSED " + _short(outcome.reason, 60)
    if not outcome.errors:
        return "FAIL " + _short(outcome.reason, 50)
    return f"FAIL p={outcome.order:.1f} err {outcome.errors[1]:.1e}"


def _cell(outcomes):
    """One table cell from the outcomes of the three azimuthal orders."""
    status = {o.status for o in outcomes}
    if len(status) == 1 and status <= {"PASS", "FAIL"} and all(o.errors for o in outcomes):
        orders = [o.order for o in outcomes]
        errs = max(o.errors[1] for o in outcomes)
        tail = "" if status == {"PASS"} else f" err {errs:.1e}"
        return f"{status.pop()} p={min(orders):.1f}–{max(orders):.1f}{tail}"
    if status == {"REFUSED"} and len({o.reason for o in outcomes}) == 1:
        return "REFUSED " + _short(outcomes[0].reason, 60)
    return "<br>".join(f"m={m} {_one(o)}" for m, o in zip(M_VALUES, outcomes))


def run(cores, m_values, cases=CASES):
    results = {}
    for case in cases:
        for core in cores:
            for geometry in GEOMETRIES:
                outcomes = []
                for m in m_values:
                    out = measure(case, core, geometry, m)
                    outcomes.append(out)
                    print(f"{case.name:28s} {core:11s} {geometry:5s} m={m} "
                          f"{out.status:8s} order {out.order:6.2f} {_short(out.reason, 60)}",
                          flush=True)
                results[(case.name, core, geometry)] = outcomes
    return results


def write_markdown(results, cores, m_values, path):
    columns = [(core, geom) for core in cores for geom in GEOMETRIES]
    lines = [
        "# Operator coverage",
        "",
        f"Generated by `scripts/operator_coverage.py` at commit `{_commit()}`.",
        "Do not edit by hand.",
        "",
        "Every cell is a manufactured-solution boundary-value problem for that",
        "operator on that (core, geometry), solved at two resolutions at",
        f"m = {', '.join(str(m) for m in m_values)}; `p` is the measured order",
        "between them (a range over the azimuthal orders). The operator string",
        "is evaluated twice, once in the IR namespace to build the problem and",
        "once symbolically to build its source, so nothing is written down",
        "twice. `tests/analytic/manufactured.py` documents how each core is",
        "driven and `tests/test_operator_coverage.py` asserts these cells.",
        "",
        "Resolutions and expected order:",
        "",
    ]
    for core in cores:
        spec = CORE_SPECS[core]
        expect = (f"spectral, error below {spec.tolerance:g}" if spec.order is None
                  else f"order {spec.order}, asserted at {spec.min_order}")
        lines.append(f"* `{core}` — {spec.label}; N = {spec.resolutions[0]}, "
                     f"{spec.resolutions[1]}; {expect}.")
    lines += ["", "| Operator | " + " | ".join(f"{c} {g}" for c, g in columns) + " |",
              "|---|" + "---|" * len(columns)]
    for case in CASES:
        row = [f"`{case.name}`"]
        for core, geom in columns:
            outs = results.get((case.name, core, geom))
            row.append("not run" if outs is None else _cell(outs))
        lines.append("| " + " | ".join(row) + " |")
    failing = [(op, core, geom, m, o)
               for (op, core, geom), outs in results.items()
               for m, o in zip(M_VALUES, outs) if o.status == "FAIL"]
    lines += ["", "## Failing cells", ""]
    if not failing:
        lines.append("None.")
    else:
        lines += ["A failing cell is a core that compiled the operator and then",
                  "did not reproduce the manufactured solution: neither a",
                  "convergence nor a refusal. Diagnose each one; do not",
                  "loosen the assertion.", "",
                  "| Operator | core | geometry | m | errors | order |",
                  "|---|---|---|---|---|---|"]
        for op, core, geom, m, o in sorted(failing):
            errs = ", ".join(f"{e:.2e}" for e in o.errors) or _short(o.reason, 40)
            lines.append(f"| `{op}` | {core} | {geom} | {m} | {errs} | "
                         f"{o.order:.2f} |")
    lines += ["", "## Operator strings", "",
              "| Operator | equation term | unknown → image |", "|---|---|---|"]
    for case in CASES:
        note = f" ({case.note})" if case.note else ""
        lines.append(f"| `{case.name}` | `{case.probe}`{note} | "
                     f"{case.unknown} → {case.output} |")
    lines += ["", "## Not in the IR vocabulary", "",
              "`Trace` of a rank-2 tensor has no IR node: `spdee/ir/operators.py`",
              "defines Grad, Div, Curl, Lap, LapH, Dt, Cross, Dot and Transpose",
              "only. The staggered C-grid assembler carries a `trace` component",
              "map (`_CGridOps.trace`) that no IR expression can reach, so the",
              "trace piece of a viscous stress has to be written as",
              "`bg_vec * Div(v)` or `Grad(Div(v))`, both of which are covered",
              "above.", ""]
    path.write_text("\n".join(lines))
    print(f"wrote {path}")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--cores", default=",".join(CORE_SPECS))
    ap.add_argument("--m", default="0,1,2")
    ap.add_argument("--cases", default=None,
                    help="index slice i:j into the case table, for splitting a run")
    ap.add_argument("--json", default=None)
    ap.add_argument("--from-json", nargs="*", default=None,
                    help="skip the runs and build the table from these dumps")
    ap.add_argument("--out", default=str(ROOT / "docs" / "OPERATOR_COVERAGE.md"))
    args = ap.parse_args()
    cores = [c for c in args.cores.split(",") if c]
    m_values = tuple(int(x) for x in args.m.split(","))
    if args.from_json:
        results = {}
        for name in args.from_json:
            for key, outs in json.loads(Path(name).read_text()).items():
                core = key.split("|")[1]
                results[tuple(key.split("|"))] = [
                    verdict(core, o["errors"]) if o["errors"]
                    else Outcome(o["status"], reason=o["reason"]) for o in outs]
        cores = [c for c in CORE_SPECS if any(k[1] == c for k in results)]
    else:
        lo, hi = (0, len(CASES)) if not args.cases else (
            int(x) for x in args.cases.split(":"))
        results = run(cores, m_values, CASES[lo:hi])
    write_markdown(results, cores, m_values, Path(args.out))
    if args.json and not args.from_json:
        dump = {"|".join(k): [{"status": o.status, "order": o.order, "reason": o.reason,
                               "errors": list(o.errors)} for o in v]
                for k, v in results.items()}
        Path(args.json).write_text(json.dumps(dump, indent=1))
        print(f"wrote {args.json}")


if __name__ == "__main__":
    main()
